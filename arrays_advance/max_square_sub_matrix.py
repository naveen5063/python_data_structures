    def get_column_pf(self, A, columns, rows):
        for i in range(1, columns+1):
            for j in range(1, rows):
                A[j][i-1] += A[j-1][i-1]
        return A

    def get_row_pf(self, A, columns, rows):
        for i in range(1, rows+1):
            for j in range(1, columns):
                A[i-1][j] += A[i-1][j-1]
